"""Appendix table of mirror structure per model (left-right and up-down, first and second half of the blocks).

Reads results/MUST-04/<model>/{metrics.json,layers.csv,blocks.csv} and results/CORE-04/structure/<model>/... and
configs/models/<model>.yaml (recipe_flip), and writes paper/sections/structure_table.tex. Nothing is typed by hand.
The MUST-12 controlled pilots are deliberately not read.

    .venv/Scripts/python.exe scripts/make_paper_structure_table.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "sections" / "structure_table.tex"
NAMES = {"dinov2_vits14_reg": "DINOv2-S/14 reg", "dinov2_vitb14": "DINOv2-B/14", "dinov2_vitb14_reg": "DINOv2-B/14 reg",
         "dinov2_vitl14_reg": "DINOv2-L/14 reg", "dinov2_vitg14_reg": "DINOv2-g/14 reg", "deit3_b16": "DeiT III-B/16",
         "dino_b16": "DINO-B/16", "dinov3_b16": "DINOv3-B/16", "eva02_b14": "EVA-02-B/14", "mae_b16": "MAE-B/16",
         "clip_b16": "CLIP-B/16", "siglip2_b16": "SigLIP 2-B/16", "convnext_b": "ConvNeXt-B", "resnet50": "ResNet-50"}
ORDER = list(NAMES)


def model_dirs() -> dict:
    out = {}
    for base in (ROOT / "results" / "CORE-04" / "structure", ROOT / "results" / "MUST-04"):
        for d in base.iterdir():
            if d.is_dir() and (d / "metrics.json").exists() and d.name in NAMES:
                out[d.name] = d                     # MUST-04 wins for the four models it covers
    return out


def flip(name: str) -> str:
    p = ROOT / "configs" / "models" / f"{name}.yaml"
    m = re.search(r'recipe_flip:\s*"?([^"\n]+)', p.read_text(encoding="utf-8")) if p.exists() else None
    v = m.group(1).strip() if m else "unknown"
    return {"yes": "yes", "no": "no"}.get(v, "unknown")


def main() -> None:
    dirs = model_dirs()
    lines = ["% generated by scripts/make_paper_structure_table.py; do not edit by hand",
             "\\begin{table}[h]", "\\centering", "\\small",
             "\\caption{Mirror structure per model, first and second half of the blocks. Ratio to null of the MLP "
             "breaking share for left-right (LR) and up-down (UD) mirroring (lower is stronger), share of hidden "
             "neurons in LR twin pairs with twin correlation at least 0.5, and number of odd LR directions of the "
             "stream at the input of the first block and the output of the last, with the width $d$ (for ConvNeXt the "
             "first value is measured inside its first block). Flips: horizontal flips in the published training "
             "recipe (DINOv3 inferred from its released configurations). DINOv2-g and EVA-02 have SwiGLU MLPs.}",
             "\\label{tab:structure}", "\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{lccccccccc}", "\\toprule",
             " & & \\multicolumn{2}{c}{LR ratio} & \\multicolumn{2}{c}{UD ratio} & \\multicolumn{2}{c}{LR twins} & "
             "\\multicolumn{2}{c}{odd dirs ($d_-$)} \\\\",
             "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}",
             "Model & Flips & early & late & early & late & early & late & first ($d$) & last ($d$) \\\\", "\\midrule"]
    for name in ORDER:
        if name not in dirs:
            continue
        d = dirs[name]
        g = json.loads((d / "metrics.json").read_text(encoding="utf-8"))["groups"]
        r = lambda G, h: g[G]["ranges"][h]["ratio_to_null"]  # noqa: E731
        lay = pd.read_csv(d / "layers.csv"); lay = lay[lay.group == "LR"].sort_values("layer")
        blk = pd.read_csv(d / "blocks.csv"); blk = blk[blk.group == "LR"].sort_values("block")
        h = len(blk) // 2
        tw_e, tw_l = blk.frac_2_t50.iloc[:h].mean(), blk.frac_2_t50.iloc[h:].mean()
        row = (f"{NAMES[name]} & {flip(name)} & {r('LR', 'first_half'):.2f} & {r('LR', 'second_half'):.2f} & "
               f"{r('UD', 'first_half'):.2f} & {r('UD', 'second_half'):.2f} & {tw_e:.2f} & {tw_l:.2f} & "
               f"{int(lay.d_minus.iloc[0])} ({int(lay.d.iloc[0])}) & {int(lay.d_minus.iloc[-1])} ({int(lay.d.iloc[-1])}) \\\\")
        lines.append(row)
        print(row)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
