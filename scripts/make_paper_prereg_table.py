"""Appendix table of every pre-registered prediction and its verdict, for the paper.

Reads the "Pre-registered predictions" table of FINAL_RESULTS.md (written by scripts/collect_next_phase.py) and
writes paper/sections/prereg_table.tex (a longtable: ID, prediction, value, bar, verdict). Nothing is typed by hand.

    .venv/Scripts/python.exe scripts/make_paper_prereg_table.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "FINAL_RESULTS.md"
OUT = ROOT / "paper" / "sections" / "prereg_table.tex"
MAX_VALUE = 150


def tex(s: str) -> str:
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"),
                 ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}"), ("$", "\\$")):
        s = s.replace(a, b)
    s = s.replace("\\textbackslash{}\\{", "\\{")
    s = s.replace("->", "\x00TO\x00").replace("<=", "\x00LE\x00").replace(">=", "\x00GE\x00")
    s = s.replace("<", "$<$").replace(">", "$>$").replace("|", "$|$")
    s = s.replace("\x00TO\x00", "$\\to$").replace("\x00LE\x00", "$\\le$").replace("\x00GE\x00", "$\\ge$")
    return s


def main() -> None:
    text = SRC.read_text(encoding="utf-8")
    block = text.split("## Pre-registered predictions", 1)[1].split("\n## ", 1)[0]
    rows = []
    for line in block.splitlines():
        if not line.startswith("| ") or line.startswith("| ID") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]]
        if len(cells) < 7:
            continue
        pid, pred, value, bar, _n, verdict = cells[:6]
        verdict = verdict.replace("*", "")
        if len(value) > MAX_VALUE:
            value = value[:MAX_VALUE].rsplit(";", 1)[0] + "; ..."
        rows.append((pid, pred, value, bar, verdict))
    out = ["% generated by scripts/make_paper_prereg_table.py from FINAL_RESULTS.md; do not edit by hand",
           "{\\footnotesize",
           "\\begin{longtable}{@{}p{1.55cm}p{5.6cm}p{3.6cm}p{2.3cm}p{1.05cm}@{}}",
           "\\caption{Every pre-registered prediction, the value we measured, the bar and the verdict.}"
           "\\label{tab:prereg}\\\\",
           "\\toprule ID & Prediction & Value & Bar & Verdict \\\\ \\midrule \\endfirsthead",
           "\\toprule ID & Prediction & Value & Bar & Verdict \\\\ \\midrule \\endhead",
           "\\bottomrule \\endfoot"]
    for pid, pred, value, bar, verdict in rows:
        out.append(f"{tex(pid)} & {tex(pred)} & {tex(value)} & {tex(bar)} & \\textbf{{{tex(verdict)}}} \\\\")
    out += ["\\end{longtable}", "}"]
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    counts = {v: sum(1 for r in rows if r[4] == v) for v in ("PASS", "FAIL", "PENDING", "REPORTED")}
    print(f"{len(rows)} rows -> {OUT}; {counts}")


if __name__ == "__main__":
    main()
