"""Appendix table: zero-shot Mirror Surgery against plain SVD and SVD-LLM on the first half of eight models (CORE-04).

Reads results/CORE-04/surgery/rows_<model>.csv (status ok rows) and writes paper/sections/core04_table.tex.

    .venv/Scripts/python.exe scripts/make_paper_core04_table.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "sections" / "core04_table.tex"
NAMES = {"dinov2_vits14_reg": "DINOv2-S/14 reg", "dinov2_vitb14": "DINOv2-B/14", "dinov2_vitb14_reg": "DINOv2-B/14 reg",
         "dinov2_vitl14_reg": "DINOv2-L/14 reg", "deit3_b16": "DeiT III-B/16", "dino_b16": "DINO-B/16",
         "mae_b16": "MAE-B/16", "siglip2_b16": "SigLIP 2-B/16"}
EOL = " " + "\\" + "\\"          # LaTeX row end


def main() -> None:
    rows = []
    for name, label in NAMES.items():
        f = ROOT / "results" / "CORE-04" / "surgery" / f"rows_{name}.csv"
        if not f.exists():
            print("missing", f)
            continue
        d = pd.read_csv(f)
        d = d[d.status == "ok"]
        orig = d[d.method == "original"].val_top1
        sizes = sorted([s for s in d["size"].unique() if s != "original"], key=lambda s: ("both" in s, s))
        if not len(orig) or len(sizes) < 2:
            print("incomplete", name, sizes)
            continue
        cells = [label, f"{orig.iloc[0]:.2f}"]
        for s in sizes:
            for m in ("mirror_exact", "svd", "svdllm"):
                v = d[(d["size"] == s) & (d.method == m)].val_top1
                cells.append(f"{v.iloc[0]:.2f}" if len(v) else "--")
        rows.append(" & ".join(cells) + EOL + f"  % sizes {sizes}")
        print(rows[-1])
    lines = [r"% generated by scripts/make_paper_core04_table.py; do not edit by hand",
             r"\begin{table}[h]", r"\centering", r"\small",
             r"\caption{Zero-shot Mirror Surgery on the first half of the blocks of eight models, against plain SVD and "
             r"SVD-LLM at matched parameter counts ($k$-NN top-1 on ImageNet validation; no healing). MLP: MLPs only; "
             r"both: MLP and attention. DINOv2-L converts 12 of its 24 blocks.}",
             r"\label{tab:core04}", r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{lccccccc}", r"\toprule",
             r" & & \multicolumn{3}{c}{first half, MLP} & \multicolumn{3}{c}{first half, both}" + EOL,
             r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
             r"Model & Original & Mirror & SVD & SVD-LLM & Mirror & SVD & SVD-LLM" + EOL, r"\midrule"]
    lines += rows + [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
