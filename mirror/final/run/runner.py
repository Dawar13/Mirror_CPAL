def proc_starttime(pid: int) -> str | None:
    """Field 22 of /proc/<pid>/stat (start time in clock ticks), or None if the process is gone."""
    try:
        stat = Path(f"/proc/{pid}/stat").read_text()
    except OSError:
        return None
    rest = stat[stat.rfind(")") + 2:].split()
    return rest[19] if len(rest) > 19 else None


def pid_alive(pid: int, starttime: str | None) -> bool:
    """True if `pid` runs, is not a zombie and is the same process (same start time; guards against pid reuse)."""
    if Path("/proc").is_dir():
        try:
            stat = Path(f"/proc/{pid}/stat").read_text()
        except OSError:
            return False
        rest = stat[stat.rfind(")") + 2:].split()
        if not rest or rest[0] == "Z":
            return False
        return starttime in (None, "") or (len(rest) > 19 and rest[19] == starttime)
    try:
        os.kill(pid, 0)
    except (OSError, SystemError):
        return False
    return True


def nvidia_smi_query(timeout: float = 15.0) -> dict | None:
    """One reading of the GPU (index $FP_GPU_INDEX, default 0): utilisation 0..1 and memory in MB, or None."""
    fields_ = "utilization.gpu,utilization.memory,memory.used,memory.free,memory.total,power.draw,temperature.gpu"
    try:
        out = subprocess.run(["nvidia-smi", "-i", os.environ.get("FP_GPU_INDEX", "0"), f"--query-gpu={fields_}",
                              "--format=csv,noheader,nounits"], capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0 or not out.stdout.strip():
        return None

    def num(x):
        try:
            return float(x.strip())
        except ValueError:
            return None

    v = [num(x) for x in out.stdout.strip().splitlines()[0].split(",")]
    if len(v) < 5 or v[3] is None or v[4] is None:
        return None
    return {"util": None if v[0] is None else v[0] / 100.0, "mem_util": None if v[1] is None else v[1] / 100.0,
            "used_mb": v[2], "free_mb": v[3], "total_mb": v[4], "power_w": v[5] if len(v) > 5 else None,
            "temp_c": v[6] if len(v) > 6 else None}


def host_available_gb() -> float | None:
    try:
        for line in Path("/proc/meminfo").read_text().splitlines():
            if line.startswith("MemAvailable:"):
                return int(line.split()[1]) / 2 ** 20
    except (OSError, ValueError, IndexError):
        pass
    return None


def container_start_epoch() -> int | None:
    """When PID 1 of this machine or container started (epoch seconds): it changes when the VM starts again after
    a pause, which the VM clock uses to leave paused time out of the budget."""
    try:
        btime = next(int(x.split()[1]) for x in Path("/proc/stat").read_text().splitlines() if x.startswith("btime"))
        ticks = int(proc_starttime(1))
        return int(round(btime + ticks / os.sysconf("SC_CLK_TCK")))
    except (OSError, ValueError, TypeError, StopIteration, AttributeError):
        return None


_WRAPPER = r'''state="$1"; id="$2"; log="$3"; root="$4"
st=$(awk '{sub(/^.*\) /, ""); print $20}' "/proc/$$/stat" 2>/dev/null || true)
echo "$$ $st" > "$state/$id.pid.tmp" && mv -f "$state/$id.pid.tmp" "$state/$id.pid"
trap 'echo "== signal received $(date -u "+%F %T")" >> "$log"' TERM INT HUP
cd "$root" || { echo 127 > "$state/$id.rc"; exit 0; }
{ echo "== start $(date -u '+%F %T') job $id pid $$ host $(hostname 2>/dev/null)"
  echo "== cmd $(head -c 2000 "$state/$id.cmd")"; } >> "$log"
bash "$state/$id.cmd" >> "$log" 2>&1 < /dev/null
rc=$?
echo "$rc" > "$state/$id.rc.tmp" && mv -f "$state/$id.rc.tmp" "$state/$id.rc"
echo "== end rc=$rc $(date -u '+%F %T')" >> "$log"
'''


class PosixLauncher:
    """Starts every job in a new session (its own process group) through a bash wrapper that records the pid, the
    exit code and the log; signals only groups whose leader pid and start time it recorded."""

    def __init__(self):
        self.children = {}

    def launch(self, job: Job, log_path: Path, state_dir: Path, cwd: Path, env: dict) -> None:
        log_path.parent.mkdir(parents=True, exist_ok=True)
        p = subprocess.Popen(["bash", "-c", _WRAPPER, "fp_runner_job", str(state_dir), job.id, str(log_path),
                              str(cwd)], cwd=str(cwd), env=env, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL, start_new_session=True, close_fds=True)
        self.children[p.pid] = p

    def alive(self, pid: int, starttime: str | None) -> bool:
        return pid_alive(pid, starttime)

    def signal_group(self, pid: int, starttime: str | None, sig: int) -> bool:
        if not pid_alive(pid, starttime):
            return False
        try:
            if os.getpgid(pid) != pid:          # not the leader of its own group: not a group we started
                return False
            os.killpg(pid, sig)
            return True
        except (ProcessLookupError, PermissionError, OSError):
            return False

    def reap(self) -> None:
        for pid, p in list(self.children.items()):
            if p.poll() is not None:
                del self.children[pid]


class SimulatedLauncher:
    """Jobs that 'run' for a set time on the runner's clock (dry runs): exit code from `outcomes` (one per attempt,
    default 0); the done marker is written on success."""

    def __init__(self, clock, root: Path, durations: dict | None = None, default_s: float = 600.0,
                 outcomes: dict | None = None):
        self.clock, self.root = clock, Path(root)
        self.durations, self.default_s, self.outcomes = durations or {}, default_s, outcomes or {}
        self.procs, self.next_pid, self.launched, self.signals = {}, 1000, [], []

    def launch(self, job: Job, log_path: Path, state_dir: Path, cwd: Path, env: dict) -> None:
        pid, self.next_pid = self.next_pid, self.next_pid + 1
        n = sum(1 for x in self.launched if x == job.id)
        rcs = self.outcomes.get(job.id, [])
        self.procs[pid] = {"job": job, "state": Path(state_dir), "end": self.clock() + self.durations.get(
            job.id, self.default_s), "rc": rcs[n] if n < len(rcs) else 0, "done": False}
        (Path(state_dir) / f"{job.id}.pid").write_text(f"{pid} sim")
        log_path.parent.mkdir(parents=True, exist_ok=True)
        log_path.write_text(f"== simulated start {job.id}\n")
        self.launched.append(job.id)

    def _finish(self, pid, rc):
        p = self.procs[pid]
        if p["done"]:
            return
        p["done"] = True
        if rc == 0 and p["job"].done:
            f = self.root / p["job"].done
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text("simulated\n")
        (p["state"] / f"{p['job'].id}.rc").write_text(str(rc))

    def alive(self, pid: int, starttime) -> bool:
        p = self.procs.get(pid)
        if p is None or p["done"]:
            return False
        if self.clock() >= p["end"]:
            self._finish(pid, p["rc"])
            return False
        return True

    def signal_group(self, pid: int, starttime, sig: int) -> bool:
        if not self.alive(pid, starttime):
            return False
        self.signals.append((pid, sig))
        self._finish(pid, 128 + int(sig))
        return True

    def reap(self) -> None:
        for pid in list(self.procs):
            self.alive(pid, None)


