class Runner:
    def __init__(self, manifest: Manifest, root=None, *, clock=time.time, gpu=None, launcher=None, host_mem=None,
                 boot_time=None, prereg=None, sleep=time.sleep, log=None):
        self.m, self.s = manifest, manifest.settings
        self.root = Path(root) if root is not None else REPO_ROOT
        self.clock, self.sleep = clock, sleep
        self.gpu_query = gpu if gpu is not None else nvidia_smi_query
        self.launcher = launcher if launcher is not None else PosixLauncher()
        self.host_mem = host_mem if host_mem is not None else host_available_gb
        self.boot_time = boot_time if boot_time is not None else container_start_epoch
        self.prereg = prereg if prereg is not None else default_prereg
        self.state = self.root / self.s.state_dir
        self.logdir = self.root / self.s.log_dir
        self.util = deque()
        self.gpu_last = None
        self.last_gpu_log = float("-inf")
        self.last_status = float("-inf")
        self.last_gpu_start = float("-inf")
        self.exit_code = None
        self._say = log
        self._interrupted = False
        self.last_reasons = {}
        self._memo = None           # per-step caches (None outside a step)
        self._starts = None

    # ------------------------------------------------------------------ files
    def _p(self, jid: str, suffix: str) -> Path:
        return self.state / f"{jid}{suffix}"

    @staticmethod
    def _read_json(path: Path, default=None):
        try:
            return json.loads(Path(path).read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return default

    @staticmethod
    def _write_json(path: Path, obj) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(json.dumps(obj, indent=1, default=str), encoding="utf-8")
        os.replace(tmp, path)

    def log(self, msg: str) -> None:
        line = f"[{_utc(self.clock())}] {msg}"
        if self._say is not None:
            self._say(line)
        else:
            print(line, flush=True)
        try:
            self.logdir.mkdir(parents=True, exist_ok=True)
            with open(self.logdir / "runner.log", "a", encoding="utf-8") as fh:
                fh.write(line + "\n")
        except OSError:
            pass

    def event(self, name: str, **kw) -> dict:
        ev = {"utc": _utc(self.clock()), "epoch": self.clock(), "event": name, **kw}
        self.state.mkdir(parents=True, exist_ok=True)
        with open(self.state / "events.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(ev, default=str) + "\n")
        return ev

    def history(self, jid: str) -> dict:
        h = self._read_json(self._p(jid, ".json"), None) or {}
        h.setdefault("attempts", [])
        h.setdefault("recorded", 0)
        h.setdefault("failures", 0)
        h.setdefault("lost", 0)
        h.setdefault("resets", [])
        return h

    def _start(self, jid: str) -> dict:
        """<id>.start (cached for the length of one step)."""
        if self._starts is not None and jid in self._starts:
            return self._starts[jid]
        v = self._read_json(self._p(jid, ".start"), None)
        if self._starts is not None:
            self._starts[jid] = v
        return v

    def _done_exists(self, job: Job) -> bool:
        return bool(job.done) and (self.root / job.done).exists()

    def _pid(self, jid: str):
        txt = None
        try:
            txt = self._p(jid, ".pid").read_text().strip()
        except OSError:
            return None, None
        parts = txt.split()
        try:
            return int(parts[0]), (parts[1] if len(parts) > 1 else None)
        except (ValueError, IndexError):
            return None, None

    def _rc(self, jid: str):
        try:
            return int(self._p(jid, ".rc").read_text().strip())
        except (OSError, ValueError):
            return None

    # ------------------------------------------------------------------ VM clock
    def clock_file(self) -> Path:
        return self.state / "budget.json"

    def clock_update(self, now: float, write: bool = True) -> float:
        """VM hours used since the start of W0 (paused time left out; see container_start_epoch)."""
        b = self._read_json(self.clock_file(), None)
        boot = self.boot_time()
        if b is None:
            b = {"w0_start_epoch": now, "w0_start_utc": _utc(now), "counted_s": 0.0, "last_seen_epoch": now,
                 "boot_epoch": boot, "pauses": [], "adjust_s": 0.0, "source": "runner"}
            if write:
                self.event("clock_start", w0_start_utc=_utc(now))
        else:
            last = float(b.get("last_seen_epoch") or b["w0_start_epoch"])
            counted = float(b.get("counted_s") or 0.0)
            old = b.get("boot_epoch")
            if boot is not None and old is not None and boot > float(old) + 5 and boot > last:
                down = boot - last
                counted += min(HEARTBEAT_SLACK_S, down) + max(0.0, now - boot)
                b.setdefault("pauses", []).append({"from_utc": _utc(last), "to_utc": _utc(boot),
                                                   "hours": round(down / 3600, 3)})
                if write:
                    self.event("pause_detected", from_utc=_utc(last), to_utc=_utc(boot), hours=round(down / 3600, 3))
                    self.log(f"VM pause detected: {down / 3600:.2f} h between {_utc(last)} and {_utc(boot)} "
                             f"not counted as VM time")
            else:
                counted += max(0.0, now - last)
            b.update(counted_s=counted, last_seen_epoch=now, boot_epoch=boot if boot is not None else old)
        if write:
            self._write_json(self.clock_file(), b)
        return (float(b.get("counted_s") or 0.0) + float(b.get("adjust_s") or 0.0)) / 3600.0

    # ------------------------------------------------------------------ attempts and states
    def _current(self, job: Job, now: float):
        """(history including an attempt that ended but is not recorded yet, running?, new record or None)."""
        if self._memo is not None and job.id in self._memo:
            return self._memo[job.id]
        res = self._current_uncached(job, now)
        if self._memo is not None:
            self._memo[job.id] = res
        return res

    def _current_uncached(self, job: Job, now: float):
        h = self.history(job.id)
        start = self._start(job.id)
        if not start or int(start.get("attempt", 0)) <= h["recorded"]:
            return h, False, None
        rc = self._rc(job.id)
        term = self._read_json(self._p(job.id, ".term"), None)
        if rc is None:
            pid, st = self._pid(job.id)
            if pid is not None:
                if self.launcher.alive(pid, st):
                    return h, True, None
                rc = self._rc(job.id)               # the wrapper may have written it meanwhile
            elif now - float(start.get("epoch", now)) < self.s.grace_s:
                return h, True, None
        if rc is None:
            if term:
                outcome = {"ceiling": "terminated", "timeout": "timeout", "service_stop": "stopped"}.get(
                    term.get("why"), "lost")
            else:
                outcome = "lost_done" if self._done_exists(job) and not job.service else "lost"
        elif term and term.get("why") == "ceiling":
            outcome = "terminated"
        elif term and term.get("why") == "timeout":
            outcome = "timeout"
        elif term and term.get("why") == "service_stop":
            outcome = "stopped"
        elif rc == 0:
            outcome = "finished" if (job.service or self._done_exists(job)) else "incomplete"
        else:
            outcome = "failed"
        rec = {"n": int(start.get("attempt", 1)), "start": start.get("epoch"), "end": now, "rc": rc,
               "outcome": outcome, "seconds": round(now - float(start.get("epoch", now)), 1)}
        h = dict(h)
        h["attempts"] = h["attempts"] + [rec]
        h["recorded"] = rec["n"]
        if outcome in FAILURES:
            h["failures"] = h["failures"] + 1
        if outcome == "lost":
            h["lost"] = h["lost"] + 1
        return h, False, rec

    def _record_ends(self, now: float) -> list:
        events = []
        for job in self.m.jobs:
            h, running, rec = self._current(job, now)
            if rec is None:
                continue
            self._write_json(self._p(job.id, ".json"), h)
            ev = self.event("end", job=job.id, attempt=rec["n"], rc=rec["rc"], outcome=rec["outcome"],
                            seconds=rec["seconds"])
            events.append(ev)
            self.log(f"end {job.id} attempt {rec['n']}: {rec['outcome']} (rc {rec['rc']}, {rec['seconds']:.0f} s)")
        return events

    def _cuts(self) -> dict:
        return self._read_json(self.state / "cuts.json", None) or {"cuts": [], "jobs": []}

    def _base(self, job: Job, now: float, cut_ids: set):
        h, running, _ = self._current(job, now)
        if running:
            return "running", "", h
        last_reset = h["resets"][-1]["attempts_before"] if h["resets"] else 0
        recent = h["attempts"][last_reset:]
        last = recent[-1]["outcome"] if recent else None
        if last in SUCCESS:
            return "finished", "", h
        if last == "terminated":
            return "terminated", "stopped by the budget governor", h
        if self._p(job.id, ".skip").exists():
            return "skipped", "skipped by hand (.skip file)", h
        if job.id in cut_ids:
            return "cut", "cut by the projection (Section 9 order)", h
        if h["failures"] >= self.s.max_failures:
            return "failed", f"failed {h['failures']} times (last {last}); see {self.s.log_dir}/{job.id}.log", h
        if h["lost"] >= self.s.max_lost:
            return "gave_up", f"lost {h['lost']} times without an exit code", h
        if not recent and not job.service and self._done_exists(job):
            return "done", "done marker present", h
        why = f"retry after {h['failures']} failure(s)" if h["failures"] else (
            f"restart after {h['lost']} loss(es)" if h["lost"] else "")
        return "pending", why, h

    def states(self, now: float, used_h: float):
        """{id: state}, {id: reason}, {id: history} for every job (no files written)."""
        cut_ids = set(self._cuts().get("jobs", []))
        states, reasons, hist = {}, {}, {}
        heal_stop = used_h >= self.s.heal_stop_hours
        ceiling = used_h >= self.s.ceiling_hours
        by_wave = {}
        for j in self.m.jobs:
            by_wave.setdefault(j.wave, []).append(j.id)
        others_open = None
        for jid in self.m.order:
            job = self.m.by_id[jid]
            st, why, h = self._base(job, now, cut_ids)
            hist[jid] = h
            if st == "pending":
                st, why = self._readiness(job, states, by_wave, heal_stop, ceiling, why)
            states[jid], reasons[jid] = st, why
        # services: not needed once every other job is settled
        others_open = any(states[j.id] not in TERMINAL for j in self.m.jobs if not j.service)
        for j in self.m.jobs:
            if j.service and not others_open and states[j.id] not in TERMINAL and states[j.id] != "running":
                states[j.id], reasons[j.id] = "not_needed", "every other job is settled"
        return states, reasons, hist

    def _readiness(self, job: Job, states: dict, by_wave: dict, heal_stop: bool, ceiling: bool, why: str):
        for d in job.deps:
            sd = states[d]
            if sd in OK_STATES:
                continue
            if sd == "cut":
                return "cut", f"dependency {d} cut"
            if sd in ("skipped", "not_needed"):
                return "not_needed", f"dependency {d} not run ({sd})"
            if sd in ("failed", "gave_up", "blocked", "terminated", "budget"):
                return "blocked", f"dependency {d} {sd}"
            return "waiting", f"waiting for {d} ({sd})"
        for a in job.after:
            ids = by_wave.get(a, []) if a in self.s.waves else [a]
            open_ = [x for x in ids if states.get(x) not in TERMINAL]
            if open_:
                return "waiting", f"after {a}: {len(open_)} job(s) open"
        for b in self.s.barrier_waves:
            if job.wave_index > self.s.waves.index(b):
                open_ = [x for x in by_wave.get(b, []) if states.get(x) not in TERMINAL]
                if open_:
                    return "waiting", f"waiting for {b} to finish ({len(open_)} job(s) open)"
        for c in job.when:
            ok = eval_condition(c, self.root)
            if ok is None:
                return "waiting", f"waiting for {c.file}"
            if not ok:
                return "not_needed", f"condition false: {c.describe()}"
        if ceiling:
            return "budget", "ceiling reached"
        if heal_stop and (job.kind == "heal" or job.kind not in self.s.after_heal_stop_kinds):
            return "budget", f"not started: VM hours passed {self.s.heal_stop_hours}"
        return "ready", why

    # ------------------------------------------------------------------ GPU
    def _gpu(self, now: float):
        try:
            g = self.gpu_query()
        except Exception:                     # noqa: BLE001 - a failed query must never stop the runner
            g = None
        self.gpu_last = g
        if g and g.get("util") is not None:
            self.util.append((now, float(g["util"])))
        while self.util and now - self.util[0][0] > self.s.util_window_s:
            self.util.popleft()
        return g

    def util_mean(self):
        return None if not self.util else sum(u for _, u in self.util) / len(self.util)

    def _gpu_log(self, now: float, used_h: float, states: dict) -> None:
        if now - self.last_gpu_log < self.s.gpu_log_s:
            return
        self.last_gpu_log = now
        f = self.root / self.s.gpu_csv
        f.parent.mkdir(parents=True, exist_ok=True)
        new = not f.exists()
        g = self.gpu_last or {}
        run = [j for j in self.m.jobs if states.get(j.id) == "running"]

        def cell(v, scale=1.0, nd=0):
            return "" if v is None else f"{v * scale:.{nd}f}"

        with open(f, "a", encoding="utf-8") as fh:
            if new:
                fh.write("utc,vm_hours,gpu_util_pct,mem_util_pct,mem_used_mib,mem_free_mib,mem_total_mib,power_w,"
                         "temp_c,running_jobs,running_heals\n")
            fh.write(",".join([_utc(now), f"{used_h:.3f}", cell(g.get("util"), 100), cell(g.get("mem_util"), 100),
                               cell(g.get("used_mb")), cell(g.get("free_mb")), cell(g.get("total_mb")),
                               cell(g.get("power_w"), 1, 1), cell(g.get("temp_c")), str(len(run)),
                               str(sum(j.kind == "heal" for j in run))]) + "\n")

    # ------------------------------------------------------------------ projection and cuts
    def _rate(self, states: dict, hist: dict):
        p = self.s.projection
        if p.source == "manual" or (p.hours_per_unit and p.concurrency):
            if p.hours_per_unit and p.concurrency:
                return {"hours_per_unit": float(p.hours_per_unit), "concurrency": float(p.concurrency),
                        "source": "manual", "n_jobs": 0}
            return None

        def from_jobs(exclude_first_wave: bool):
            iv, units = [], 0.0
            for j in self.m.jobs:
                if j.kind != "heal" or (exclude_first_wave and j.wave_index == 0):
                    continue
                for a in hist[j.id]["attempts"]:
                    if a["outcome"] in ("finished", "lost_done") and a.get("start") and a.get("end"):
                        iv.append((float(a["start"]), float(a["end"])))
                        units += j.heal_units
            if not iv or units <= 0:
                return None
            wall = sum(e - s for s, e in iv)
            union, cur_s, cur_e = 0.0, None, None
            for s, e in sorted(iv):
                if cur_e is None or s > cur_e:
                    if cur_e is not None:
                        union += cur_e - cur_s
                    cur_s, cur_e = s, e
                else:
                    cur_e = max(cur_e, e)
            union += cur_e - cur_s
            if union <= 0:
                return None
            return {"hours_per_unit": wall / 3600.0 / units, "concurrency": max(1.0, wall / union),
                    "source": "jobs", "n_jobs": len(iv)}

        def from_file():
            t = self._read_json(self.root / p.timing_file, None)
            try:
                return {"hours_per_unit": float(t["hours_per_unit"]), "concurrency": max(1.0, float(t["concurrency"])),
                        "source": f"timing file {p.timing_file}", "n_jobs": 0}
            except (TypeError, KeyError, ValueError):
                return None

        if p.source == "timing_file":
            return from_file()
        if p.source == "jobs":
            return from_jobs(False)
        later = from_jobs(True)
        if later and later["n_jobs"] >= p.min_heal_jobs:
            return later
        return from_file() or from_jobs(False)

    def projection(self, now: float, used_h: float, states: dict, hist: dict, cut_extra=()) -> dict:
        p = self.s.projection
        rate = self._rate(states, hist)
        out = {"used_hours": used_h, "target_hours": p.target_hours, "available": rate is not None}
        if rate is None:
            out["why"] = "no measured heal time yet (no W0 timing file and no finished heal job)"
            return out
        eff = rate["hours_per_unit"] / rate["concurrency"]
        remaining, overhead, n_left = 0.0, 0.0, 0
        for j in self.m.jobs:
            st = states[j.id]
            if j.id in cut_extra or (st in TERMINAL):
                continue
            if j.kind == "heal":
                if st == "running":
                    start = (self._start(j.id) or {})
                    run_h = max(0.0, now - float(start.get("epoch", now))) / 3600.0
                    frac = max(0.0, 1.0 - run_h / max(1e-9, j.heal_units * rate["hours_per_unit"]))
                    remaining += j.heal_units * frac
                else:
                    remaining += j.heal_units
                    n_left += 1
            elif not j.overlap:
                overhead += j.est_hours
        total = used_h + remaining * eff + overhead + p.reserve_hours
        out.update({"hours_per_unit": rate["hours_per_unit"], "concurrency": rate["concurrency"],
                    "rate_source": rate["source"], "rate_jobs": rate["n_jobs"], "effective_hours_per_unit": eff,
                    "remaining_units": remaining, "heal_jobs_left": n_left, "serial_hours": overhead,
                    "reserve_hours": p.reserve_hours, "total_hours": total, "fits": total <= p.target_hours})
        return out

    def _trigger(self, states: dict, hist: dict):
        """The first wave after the first one that has a ready job but has never started a job, if not projected."""
        done = {x.get("trigger") for x in self._read_json(self.state / "projections.json", []) or []}
        for w in self.s.waves[1:]:
            jobs = [j for j in self.m.jobs if j.wave == w]
            if not jobs or any(hist[j.id]["attempts"] or states[j.id] == "running" for j in jobs):
                continue
            if any(states[j.id] == "ready" for j in jobs):
                if w in done:
                    continue
                if done and not self.s.recut_each_wave:
                    return None
                return w
        return None

    def plan_cuts(self, now: float, used_h: float, states: dict, hist: dict, proj: dict | None = None) -> list:
        """The cuts the Section 9 order makes to bring the projection under target_hours (nothing is written):
        [{"rank", "jobs" (the rank's unstarted jobs and their dependents), "heal_units", "before_hours",
        "after_hours"}], rank by rank, stopping as soon as the projection fits."""
        p = self.s.projection
        proj = proj or self.projection(now, used_h, states, hist)
        if not proj.get("available") or proj["fits"]:
            return []
        cut_ids = set(self._cuts()["jobs"])
        removed = set()

        def cuttable(jid):
            return states[jid] in ("pending", "waiting", "ready") and jid not in cut_ids and jid not in removed

        ranks = sorted({j.cut_rank for j in self.m.jobs if j.cut_rank is not None and cuttable(j.id)})
        out, before = [], proj["total_hours"]
        for r in ranks:
            group = [j.id for j in self.m.jobs if j.cut_rank == r and cuttable(j.id)]
            closure, stack = [], list(group)
            while stack:
                x = stack.pop(0)
                if x in closure or not cuttable(x):
                    continue
                closure.append(x)
                stack.extend(self.m.dependents.get(x, []))
            if not closure:
                continue
            removed.update(closure)
            after = self.projection(now, used_h, states, hist, cut_extra=removed)
            out.append({"rank": r, "jobs": closure, "heal_units": sum(self.m.by_id[x].heal_units for x in closure),
                        "before_hours": before, "after_hours": after["total_hours"]})
            before = after["total_hours"]
            if before <= p.target_hours:
                break
        return out

    def project_and_cut(self, trigger: str, now: float, used_h: float, states: dict, hist: dict) -> dict:
        p = self.s.projection
        proj = self.projection(now, used_h, states, hist)
        record = {"trigger": trigger, "utc": _utc(now), "epoch": now, "projection": proj, "cuts": []}
        label = "after W0" if trigger == self.s.waves[1] or not any(
            x.get("trigger") for x in self._read_json(self.state / "projections.json", []) or []) else f"before {trigger}"
        if proj.get("available") and not proj["fits"]:
            cuts = self._cuts()
            before = proj["total_hours"]
            for entry in self.plan_cuts(now, used_h, states, hist, proj):
                entry.update(trigger=trigger, utc=_utc(now))
                r, closure, units = entry["rank"], entry["jobs"], entry["heal_units"]
                record["cuts"].append(entry)
                cuts["cuts"].append(entry)
                cuts["jobs"] = sorted(set(cuts["jobs"]) | set(closure))
                self._write_json(self.state / "cuts.json", cuts)
                self.event("cut", rank=r, jobs=closure, before=entry["before_hours"], after=entry["after_hours"])
                self.log(f"cut rank {r}: {', '.join(closure)} ({units:g} heal-units); projection "
                         f"{entry['before_hours']:.2f} -> {entry['after_hours']:.2f} h")
                self._decision_line(
                    f"Section 9 cut, rank {r}: {len(closure)} job(s) not run ({', '.join(closure)}; "
                    f"{units:g} heal-units)",
                    f"Projected {entry['before_hours']:.1f} VM-hours, above the {p.target_hours:g} h target, {label} "
                    f"({proj['hours_per_unit']:.2f} h per heal-unit at concurrency {proj['concurrency']:.1f}, "
                    f"{proj['rate_source']}; {proj['remaining_units']:.1f} heal-units left)",
                    f"Projection {entry['after_hours']:.1f} h after this cut")
                before = entry["after_hours"]
            record["after_cuts"] = before
            if before > p.target_hours:
                self.log(f"projection {before:.2f} h is still above {p.target_hours} h after every allowed cut; "
                         f"the governor enforces {self.s.heal_stop_hours} and {self.s.ceiling_hours} h")
                self._decision_line(
                    f"Projection still {before:.1f} VM-hours after every allowed cut ({label})",
                    "Only never-cut jobs are left", f"The governor stops new heals at {self.s.heal_stop_hours:g} h "
                    f"and everything at {self.s.ceiling_hours:g} h")
        elif not proj.get("available"):
            self.log(f"projection {label} not available: {proj.get('why')}")
        else:
            self.log(f"projection {label}: {proj['total_hours']:.2f} VM-hours (target {p.target_hours}); no cuts")
        hist_list = self._read_json(self.state / "projections.json", []) or []
        hist_list.append(record)
        self._write_json(self.state / "projections.json", hist_list)
        self.event("projection", trigger=trigger, total=proj.get("total_hours"), cuts=len(record["cuts"]))
        return record

    def _decision_line(self, decision: str, reason: str, effect: str) -> None:
        f = self.root / self.s.decisions_file
        f.parent.mkdir(parents=True, exist_ok=True)
        text = f.read_text(encoding="utf-8") if f.exists() else ""
        line = (f"| {time.strftime('%Y-%m-%d', time.gmtime(self.clock()))} | {decision} | {reason} | {effect} | "
                f"Runner (pre-registered cut order) |\n")
        with open(f, "a", encoding="utf-8") as fh:
            if text and not text.endswith("\n"):
                fh.write("\n")
            fh.write(line)

    # ------------------------------------------------------------------ stop events
    def stop_reasons(self, states: dict, hist: dict) -> list:
        saved = self._read_json(self.state / "stop.json", None) or {}
        reasons = list(saved.get("reasons", []))
        new = []
        for j in self.m.jobs:
            if states[j.id] == "failed":
                r = f"job {j.id} failed {hist[j.id]['failures']} times; see {self.s.log_dir}/{j.id}.log"
                if r not in reasons:
                    new.append(r)
        for c in self.s.stop_when:
            if eval_condition(c, self.root):
                r = c.reason or f"stop condition: {c.describe()}"
                if r not in reasons:
                    new.append(r)
        if new:
            reasons += new
            self._write_json(self.state / "stop.json", {"stopped": True, "reasons": reasons,
                                                        "utc": _utc(self.clock())})
            for r in new:
                self.event("stop", reason=r)
                self.log(f"STOP: {r}; no new jobs start (running jobs continue)")
        return reasons

    # ------------------------------------------------------------------ signals
    def _terminate(self, job: Job, now: float, why: str) -> None:
        term = self._read_json(self._p(job.id, ".term"), None)
        pid, st = self._pid(job.id)
        if term is None:
            term = {"why": why, "epoch": now, "utc": _utc(now), "term_sent": False, "kill_sent": False}
        if pid is not None and not term.get("term_sent"):
            term["term_sent"] = bool(self.launcher.signal_group(pid, st, SIGTERM))
            term["term_epoch"] = now
            self.log(f"SIGTERM to job {job.id} (process group {pid}; {why})")
        elif pid is not None and term.get("term_sent") and not term.get("kill_sent") and \
                now - float(term.get("term_epoch", now)) >= self.s.term_grace_s:
            term["kill_sent"] = bool(self.launcher.signal_group(pid, st, SIGKILL))
            self.log(f"SIGKILL to job {job.id} (process group {pid}; {why})")
        self._write_json(self._p(job.id, ".term"), term)

    # ------------------------------------------------------------------ launching
    def _need_gb(self, job: Job, hist: dict) -> float:
        return job.gpu_mem_gb * (self.s.retry_mem_factor if hist[job.id]["failures"] else 1.0)

    def _resource_reason(self, job: Job, now: float, states: dict, hist: dict, used_h: float, rate):
        s = self.s
        running = [self.m.by_id[x] for x, st in states.items() if st == "running"]
        if len([j for j in running if not j.service]) >= s.max_running and not job.service:
            return f"max_running {s.max_running} reached"
        if job.kind == "heal" and sum(j.kind == "heal" for j in running) >= s.max_heals:
            return f"max_heals {s.max_heals} reached"
        if not job.gpu and sum(not j.gpu for j in running) >= s.max_cpu:
            return f"max_cpu {s.max_cpu} reached"
        held = {lk for j in running for lk in j.locks}
        busy = [lk for lk in job.locks if lk in held]
        if busy:
            return f"lock {','.join(busy)} held"
        if job.gpu:
            if any(j.exclusive for j in running):
                return "an exclusive job is running"
            if job.exclusive and any(j.gpu and not j.service for j in running):
                return "exclusive: waiting for the other GPU jobs to end"
            if now - self.last_gpu_start < s.stagger_s:
                return f"stagger ({s.stagger_s:g} s after the last GPU start)"
            g = self.gpu_last
            if not g:
                return "no GPU reading (nvidia-smi)"
            need = self._need_gb(job, hist)
            free = g["free_mb"] / 1024.0
            total = g["total_mb"] / 1024.0
            reserved = 0.0
            for j in running:
                if j.gpu:
                    st = (self._start(j.id) or {})
                    if now - float(st.get("epoch", 0)) < s.warmup_s:
                        reserved += float(st.get("gpu_mem_gb", j.gpu_mem_gb))
            spare = free - reserved - need
            if spare < s.headroom_gb:
                return (f"GPU memory: free {free:.1f} - reserved {reserved:.1f} - needs {need:.1f} = {spare:.1f} "
                        f"< headroom {s.headroom_gb:g} GB")
            if s.declared_budget:
                declared = sum(float(((self._start(j.id) or {})).get("gpu_mem_gb",
                                                                                                j.gpu_mem_gb))
                               for j in running if j.gpu)
                if declared + need > total - s.headroom_gb:
                    return (f"declared GPU budget: running {declared:.1f} + needs {need:.1f} > total {total:.1f} - "
                            f"headroom {s.headroom_gb:g} GB")
        if job.host_mem_gb > 0:
            avail = self.host_mem()
            if avail is not None:
                reserved = 0.0
                for j in running:
                    st = (self._start(j.id) or {})
                    if now - float(st.get("epoch", 0)) < s.warmup_s:
                        reserved += j.host_mem_gb
                if avail - reserved - job.host_mem_gb < s.host_headroom_gb:
                    return (f"host memory: available {avail:.1f} - reserved {reserved:.1f} - needs "
                            f"{job.host_mem_gb:g} < headroom {s.host_headroom_gb:g} GB")
        if job.kind == "heal" and rate is not None:
            expect_h = job.heal_units * rate["hours_per_unit"]
            if used_h + expect_h > s.ceiling_hours - s.end_reserve_hours:
                return (f"governor: would end near {used_h + expect_h:.1f} VM-hours, after "
                        f"{s.ceiling_hours - s.end_reserve_hours:g}")
        return None

    def _choose(self, now: float, states: dict, reasons: dict, hist: dict, used_h: float):
        ready = [self.m.by_id[x] for x in self.m.order if states[x] == "ready"]
        if not ready:
            return None
        heals_running = any(self.m.by_id[x].kind == "heal" for x, st in states.items() if st == "running")
        u = self.util_mean()
        low = u is not None and u < self.s.util_target

        def pref(j):
            if heals_running and low:
                return 0 if j.kind in self.s.light_kinds else 1
            return 0 if j.kind == "heal" else 1

        ready.sort(key=lambda j: (pref(j), -j.priority, j.wave_index, j.index))
        rate = self._rate(states, hist) if any(j.kind == "heal" for j in ready) else None
        for j in ready:
            why = self._resource_reason(j, now, states, hist, used_h, rate)
            if why is None:
                return j
            reasons[j.id] = why
        return None

    def launch(self, job: Job, now: float, hist: dict) -> None:
        h = hist[job.id]
        attempt = int(h["recorded"]) + 1
        for suffix in (".pid", ".rc", ".term", ".rc.tmp", ".pid.tmp"):
            self._p(job.id, suffix).unlink(missing_ok=True)
        need = self._need_gb(job, hist)
        self._write_json(self._p(job.id, ".start"), {
            "attempt": attempt, "epoch": now, "utc": _utc(now), "command": job.command, "kind": job.kind,
            "wave": job.wave, "gpu_mem_gb": need, "host_mem_gb": job.host_mem_gb})
        self._p(job.id, ".cmd").write_text(job.command + "\n", encoding="utf-8")
        env = dict(os.environ)
        env.update(self.s.env)
        env.update(job.env)
        env.update({"FP_JOB_ID": job.id, "FP_JOB_WAVE": job.wave, "FP_JOB_ATTEMPT": str(attempt),
                    "FP_RUNNER_STATE": str(self.state)})
        log_path = self.logdir / f"{job.id}.log"
        try:
            self.launcher.launch(job, log_path, self.state, self.root, env)
        except Exception as exc:              # noqa: BLE001 - recorded as a failed attempt
            self._p(job.id, ".rc").write_text("127")
            with open(log_path, "a", encoding="utf-8") as fh:
                fh.write(f"== launch failed: {type(exc).__name__}: {exc}\n")
            self.log(f"launch of {job.id} failed: {exc}")
        if job.gpu:
            self.last_gpu_start = now
        self.event("start", job=job.id, attempt=attempt, wave=job.wave, kind=job.kind, gpu_mem_gb=need)
        self.log(f"start {job.id} (wave {job.wave}, {job.kind}, attempt {attempt}, {need:g} GB): "
                 f"{job.command[:160]}")

    # ------------------------------------------------------------------ one step
    def step(self) -> dict:
        """One scheduling pass (record ends, governor, stop events, projection and cuts, at most one start)."""
        self._memo, self._starts = {}, {}
        try:
            return self._step()
        finally:
            self._memo = self._starts = None

    def _step(self) -> dict:
        now = self.clock()
        self.state.mkdir(parents=True, exist_ok=True)
        used_h = self.clock_update(now)
        self._gpu(now)
        if hasattr(self.launcher, "reap"):
            self.launcher.reap()
        events = self._record_ends(now)
        states, reasons, hist = self.states(now, used_h)
        info = {"now": now, "used_hours": used_h, "launched": None, "events": events, "finished": False,
                "stopped": False, "governor": "normal"}
        if used_h >= self.s.ceiling_hours:
            info["governor"] = "ceiling"
            if not (self.state / "ceiling.json").exists():
                self._write_json(self.state / "ceiling.json", {"utc": _utc(now), "used_hours": used_h})
                self.event("ceiling", used_hours=used_h)
                self.log(f"CEILING: {used_h:.2f} VM-hours; stopping every job this runner started")
            for j in self.m.jobs:
                if states[j.id] == "running":
                    self._terminate(j, now, "ceiling")
            if not any(st == "running" for st in states.values()):
                info["finished"] = True
                self.exit_code = 3
            self._gpu_log(now, used_h, states)
            self.write_status(now, used_h, states, reasons, hist, force=True)
            return info
        if used_h >= self.s.heal_stop_hours:
            info["governor"] = "heal_stop"
            if not (self.state / "heal_stop.json").exists():
                self._write_json(self.state / "heal_stop.json", {"utc": _utc(now), "used_hours": used_h})
                self.event("heal_stop", used_hours=used_h)
                self.log(f"GOVERNOR: {used_h:.2f} VM-hours; no new heals (stop event: report to Dawar)")
        for j in self.m.jobs:                                    # timeouts and service stops
            if states[j.id] != "running":
                continue
            term = self._read_json(self._p(j.id, ".term"), None)
            st = (self._start(j.id) or {})
            if term:
                self._terminate(j, now, term.get("why", "timeout"))
            elif j.timeout_hours and now - float(st.get("epoch", now)) > j.timeout_hours * 3600:
                self._terminate(j, now, "timeout")
        stops = self.stop_reasons(states, hist)
        info["stopped"] = bool(stops)
        # services run while other jobs run or may still start (after a stop event, only while others run)
        others_running = any(states[j.id] == "running" for j in self.m.jobs if not j.service)
        others_open = any(states[j.id] not in TERMINAL for j in self.m.jobs if not j.service)
        if not (others_running or (others_open and not stops)):
            for j in self.m.jobs:
                if j.service and states[j.id] == "running" and not self._p(j.id, ".term").exists():
                    self._terminate(j, now, "service_stop")
        if not stops:
            trig = self._trigger(states, hist)
            if trig:
                self.project_and_cut(trig, now, used_h, states, hist)
                states, reasons, hist = self.states(now, used_h)
            job = self._choose(now, states, reasons, hist, used_h)
            if job is not None:
                self.launch(job, now, hist)
                states[job.id], reasons[job.id] = "running", "started"
                info["launched"] = job.id
        else:
            for x, st in states.items():
                if st == "ready":
                    reasons[x] = "stopped: " + stops[0]
        running = any(st == "running" for st in states.values())
        if not running:
            if stops:
                info["finished"], self.exit_code = True, 2
            elif all(st in TERMINAL for st in states.values()):
                bad = [x for x, st in states.items() if st in ("failed", "gave_up", "blocked")]
                info["finished"], self.exit_code = True, (1 if bad else 0)
        info["stalled"] = (not running and not info["finished"] and info["launched"] is None
                           and not any(st == "ready" for st in states.values()))
        self.last_reasons = reasons
        self._gpu_log(now, used_h, states)
        self.write_status(now, used_h, states, reasons, hist, force=bool(events or info["launched"]
                                                                          or info["finished"]), info=info)
        return info

    def next_wait(self, now: float) -> float:
        due = min(self.last_gpu_log + self.s.gpu_log_s, now + self.s.poll_s)
        return max(1.0, due - now)

    def run(self, max_steps: int | None = None) -> int:
        """The loop: refuses to start unless the pre-registration check passes; one runner per state directory;
        SIGTERM or Ctrl-C stops the runner and leaves its jobs running (start it again to resume)."""
        st = self.prereg()
        self.log(f"pre-registration: {st.get('reason') if isinstance(st, dict) else st}")
        with RunnerLock(self.state / "runner.lock"):
            self._write_json(self.state / "runner.json", {"pid": os.getpid(), "utc": _utc(self.clock()),
                                                          "manifest": str(self.m.path), "sha256": self.m.sha256})
            old = {}
            for sig in (signal.SIGINT, getattr(signal, "SIGTERM", None), getattr(signal, "SIGHUP", None)):
                if sig is not None:
                    try:
                        old[sig] = signal.signal(sig, self._on_signal)
                    except (ValueError, OSError):
                        pass
            steps = 0
            try:
                while True:
                    info = self.step()
                    steps += 1
                    if info["finished"]:
                        self.log(f"runner finished (exit code {self.exit_code})")
                        return int(self.exit_code)
                    if self._interrupted or (max_steps is not None and steps >= max_steps):
                        self.log("runner stopped; its jobs keep running (start it again to resume)")
                        return 130 if self._interrupted else 0
                    self.sleep(self.next_wait(self.clock()))
            finally:
                for sig, h in old.items():
                    try:
                        signal.signal(sig, h)
                    except (ValueError, OSError):
                        pass

    def _on_signal(self, signum, frame):
        self._interrupted = True

    # ------------------------------------------------------------------ status
    def snapshot(self) -> dict:
        """States, reasons and the projection without changing anything (for `fp_runner.py status`)."""
        self._memo, self._starts = {}, {}
        try:
            now = self.clock()
            used_h = self.clock_update(now, write=False)
            states, reasons, hist = self.states(now, used_h)
            return {"now": now, "used_hours": used_h, "states": states, "reasons": reasons,
                    "projection": self.projection(now, used_h, states, hist), "hist": hist,
                    "stop": (self._read_json(self.state / "stop.json", None) or {}).get("reasons", []),
                    "cuts": self._cuts()}
        finally:
            self._memo = self._starts = None

    def render_status(self, now: float, used_h: float, states: dict, reasons: dict, hist: dict,
                      info: dict | None = None) -> str:
        s = self.s
        g = self.gpu_last or {}
        u = self.util_mean()
        proj = self.projection(now, used_h, states, hist)
        stops = (self._read_json(self.state / "stop.json", None) or {}).get("reasons", [])
        cuts = self._cuts()
        budget = self._read_json(self.clock_file(), {}) or {}
        if used_h >= s.ceiling_hours:
            gov = f"CEILING reached: every job stopped; the VM can be paused (Dawar decides)"
        elif used_h >= s.heal_stop_hours:
            gov = f"no new heals (passed {s.heal_stop_hours:g} h): finishing running jobs, evaluations and the report"
        else:
            gov = "normal"
        lines = [f"### Final phase runner (auto-generated {_utc(now)} UTC)", "",
                 f"- VM time since the start of W0 ({budget.get('w0_start_utc', '?')} UTC): **{used_h:.2f} h** of "
                 f"{s.ceiling_hours:g} (no new heals from {s.heal_stop_hours:g} h); governor: {gov}"
                 + (f"; {len(budget.get('pauses', []))} VM pause(s) left out" if budget.get("pauses") else "")
                 + ("" if budget.get("boot_epoch") is not None else "; pause detection unavailable on this machine "
                    "(a pause would count; correct with fp_runner.py clock --adjust-hours)"),
                 f"- Manifest: {self.m.path or '(dict)'}"
                 + (f" (sha256 {self.m.sha256[:12]})" if self.m.sha256 else "")]
        if g:
            lines.append(f"- GPU: utilisation {('%.0f%%' % (100 * g['util'])) if g.get('util') is not None else '?'} "
                         f"now, {('%.0f%%' % (100 * u)) if u is not None else '?'} mean over "
                         f"{s.util_window_s / 60:.0f} min (target {100 * s.util_target:.0f}%); memory "
                         f"{g['used_mb'] / 1024:.1f} of {g['total_mb'] / 1024:.1f} GB used; log {s.gpu_csv}")
        else:
            lines.append("- GPU: no reading")
        if proj.get("available"):
            lines.append(f"- Projection: **{proj['total_hours']:.1f} VM-hours** in total (target "
                         f"{proj['target_hours']:g}): {proj['hours_per_unit']:.2f} h per heal-unit at concurrency "
                         f"{proj['concurrency']:.1f} ({proj['rate_source']}), {proj['remaining_units']:.1f} heal-units "
                         f"left, {proj['serial_hours']:.1f} h serial work, {proj['reserve_hours']:.1f} h reserve")
        else:
            lines.append(f"- Projection: not available ({proj.get('why')})")
        lines.append("- Stop events: " + ("**" + "; ".join(stops) + "**" if stops else "none"))
        if cuts["cuts"]:
            lines.append("- Cuts (Section 9 order): " + "; ".join(
                f"rank {c['rank']} at {c['utc']}: {', '.join(c['jobs'])} ({c['before_hours']:.1f} -> "
                f"{c['after_hours']:.1f} h)" for c in cuts["cuts"]))
        else:
            lines.append("- Cuts: none")
        if info and info.get("stalled"):
            lines.append("- **Stalled**: nothing runs and nothing is ready (see the reasons below)")
        lines += ["", "| Wave | Jobs | Finished | Running | Ready or waiting | Failed or blocked | Cut, skipped, "
                      "not needed or budget | Heal-units left |", "|---|---|---|---|---|---|---|---|"]
        for w in s.waves:
            js = [j for j in self.m.jobs if j.wave == w]
            if not js:
                continue
            c = lambda names: sum(states[j.id] in names for j in js)  # noqa: E731
            left = sum(j.heal_units for j in js if states[j.id] not in TERMINAL)
            lines.append(f"| {w} | {len(js)} | {c(OK_STATES)} | {c({'running'})} | "
                         f"{c({'ready', 'waiting', 'pending'})} | {c({'failed', 'gave_up', 'blocked', 'terminated'})} | "
                         f"{c({'cut', 'skipped', 'not_needed', 'budget'})} | {left:g} |")
        lines += ["", "| Job | Wave | Kind | State | Attempts | Hours | Note |", "|---|---|---|---|---|---|---|"]
        for jid in self.m.order:
            j = self.m.by_id[jid]
            h = hist[jid]
            hours = sum(float(a.get("seconds") or 0) for a in h["attempts"]) / 3600.0
            if states[jid] == "running":
                st = self._start(jid) or {}
                hours += max(0.0, now - float(st.get("epoch", now))) / 3600.0
            n_att = len(h["attempts"]) + (1 if states[jid] == "running" else 0)
            note = (reasons.get(jid) or "").replace("|", "/")
            lines.append(f"| {jid} | {j.wave} | {j.kind} | {states[jid]} | {n_att} | {hours:.2f} | {note[:120]} |")
        return "\n".join(lines)

    def write_status(self, now: float, used_h: float, states: dict, reasons: dict, hist: dict, force: bool = False,
                     info: dict | None = None) -> None:
        if not force and now - self.last_status < self.s.status_s:
            return
        self.last_status = now
        body = self.render_status(now, used_h, states, reasons, hist, info)
        try:
            update_marked_section(self.root / self.s.status_file, body)
        except OSError as exc:
            self.log(f"could not write {self.s.status_file}: {exc}")
        self._write_json(self.state / "status.json", {
            "utc": _utc(now), "used_hours": used_h, "states": states, "reasons": reasons,
            "exit_code": self.exit_code, "util_mean": self.util_mean(), "gpu": self.gpu_last})

    # ------------------------------------------------------------------ maintenance (command line)
    def reset(self, jid: str) -> dict:
        """Clear a job's failure and loss counts (after a fix), so it can run again; history is kept."""
        if jid not in self.m.by_id:
            raise KeyError(jid)
        h = self.history(jid)
        h["resets"].append({"utc": _utc(self.clock()), "attempts_before": len(h["attempts"]),
                            "failures": h["failures"], "lost": h["lost"]})
        h["failures"], h["lost"] = 0, 0
        self._write_json(self._p(jid, ".json"), h)
        stop = self._read_json(self.state / "stop.json", None)
        if stop:
            stop["reasons"] = [r for r in stop.get("reasons", []) if not r.startswith(f"job {jid} ")]
            if stop["reasons"]:
                self._write_json(self.state / "stop.json", stop)
            else:
                (self.state / "stop.json").unlink(missing_ok=True)
        self.event("reset", job=jid)
        return h

    def clear_stop(self) -> None:
        (self.state / "stop.json").unlink(missing_ok=True)
        self.event("clear_stop")
