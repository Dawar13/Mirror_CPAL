@dataclass
class Manifest:
    settings: Settings
    jobs: list
    path: Path | None = None
    sha256: str | None = None
    by_id: dict = field(default_factory=dict)
    order: list = field(default_factory=list)          # processing order: wave, then dependencies
    dependents: dict = field(default_factory=dict)     # id -> ids with a hard dependency on it


_SETTING_TYPES = {"after_heal_stop_kinds": list, "light_kinds": list, "waves": list, "barrier_waves": list,
                  "env": dict, "stop_when": list, "projection": dict}


def _parse_settings(d: dict, errors: list) -> Settings:
    s = Settings()
    known = set(Settings.__dataclass_fields__)
    for k, v in (d or {}).items():
        if k not in known:
            errors.append(f"settings: unknown key {k!r}")
            continue
        if k == "projection":
            p = ProjectionSettings()
            for pk, pv in (v or {}).items():
                if pk not in ProjectionSettings.__dataclass_fields__:
                    errors.append(f"settings.projection: unknown key {pk!r}")
                    continue
                setattr(p, pk, pv)
            if p.source not in ("auto", "timing_file", "jobs", "manual"):
                errors.append(f"settings.projection.source {p.source!r} not one of auto, timing_file, jobs, manual")
            s.projection = p
        elif k == "stop_when":
            items = v if isinstance(v, list) else [v]
            s.stop_when = [c for c in (parse_condition(x, "settings.stop_when", errors) for x in items) if c]
        elif k in _SETTING_TYPES:
            if not isinstance(v, _SETTING_TYPES[k]):
                errors.append(f"settings.{k}: expected a {_SETTING_TYPES[k].__name__}")
                continue
            setattr(s, k, {str(a): str(b) for a, b in v.items()} if k == "env" else list(v))
        else:
            default = getattr(Settings(), k)
            try:
                setattr(s, k, type(default)(v) if not isinstance(default, bool) else bool(v))
            except (TypeError, ValueError):
                errors.append(f"settings.{k}: bad value {v!r}")
    return s


_JOB_KEYS = set(Job.__dataclass_fields__) - {"index", "wave_index"}


def _as_list(v):
    if v is None:
        return []
    return list(v) if isinstance(v, (list, tuple)) else [v]


def _parse_job(d, i: int, s: Settings, errors: list) -> Job | None:
    where = f"jobs[{i}]"
    if not isinstance(d, dict):
        errors.append(f"{where}: not a mapping")
        return None
    where = f"job {d.get('id', i)!r}"
    extra = set(d) - _JOB_KEYS
    if extra:
        errors.append(f"{where}: unknown keys {sorted(extra)}")
    for req in ("id", "wave", "kind", "command"):
        if not d.get(req):
            errors.append(f"{where}: missing {req!r}")
    if any(not d.get(r) for r in ("id", "wave", "kind", "command")):
        return None
    jid = str(d["id"])
    if not ID_RE.match(jid):
        errors.append(f"{where}: id may hold letters, digits, '_', '.', '-' only")
    if d["wave"] not in s.waves:
        errors.append(f"{where}: wave {d['wave']!r} is not in settings.waves {s.waves}")
    if d["kind"] not in KINDS:
        errors.append(f"{where}: kind {d['kind']!r} is not one of {KINDS}")
    cut = d.get("cut_rank")
    if cut in NEVER:
        cut = None
    elif not (isinstance(cut, int) and not isinstance(cut, bool) and cut >= 1):
        errors.append(f"{where}: cut_rank must be an integer >= 1 or never_cut")
        cut = None
    try:
        job = Job(id=jid, wave=str(d["wave"]), kind=str(d["kind"]), command=str(d["command"]).strip(),
                  done=d.get("done"), deps=[str(x) for x in _as_list(d.get("deps"))],
                  after=[str(x) for x in _as_list(d.get("after"))], gpu_mem_gb=float(d.get("gpu_mem_gb") or 0),
                  host_mem_gb=float(d.get("host_mem_gb") or 0), priority=int(d.get("priority") or 0),
                  heal_units=float(d.get("heal_units") or 0), cut_rank=cut, est_hours=float(d.get("est_hours") or 0),
                  overlap=bool(d.get("overlap", True)), locks=[str(x) for x in _as_list(d.get("locks"))],
                  exclusive=bool(d.get("exclusive", False)), service=bool(d.get("service", False)),
                  timeout_hours=None if d.get("timeout_hours") is None else float(d["timeout_hours"]),
                  env={str(a): str(b) for a, b in (d.get("env") or {}).items()}, note=str(d.get("note") or ""),
                  index=i, wave_index=s.waves.index(d["wave"]) if d["wave"] in s.waves else 0)
    except (TypeError, ValueError, AttributeError) as exc:
        errors.append(f"{where}: bad value ({exc})")
        return None
    job.when = [c for c in (parse_condition(x, f"{where} when", errors) for x in _as_list(d.get("when"))) if c]
    if not job.service and not job.done:
        errors.append(f"{where}: needs a done marker ('done'), the file that exists when it succeeded")
    if min(job.gpu_mem_gb, job.host_mem_gb, job.heal_units, job.est_hours) < 0:
        errors.append(f"{where}: memory, heal_units and est_hours must be >= 0")
    if job.kind == "heal" and (job.heal_units <= 0 or job.gpu_mem_gb <= 0):
        errors.append(f"{where}: a heal job needs heal_units > 0 and gpu_mem_gb > 0")
    if job.service and job.kind == "heal":
        errors.append(f"{where}: a heal job cannot be a service")
    return job


def _validate(m: Manifest, errors: list) -> None:
    s = m.settings
    seen = {}
    for j in m.jobs:
        if j.id in seen:
            errors.append(f"job {j.id!r}: duplicate id")
        seen[j.id] = j
    m.by_id = seen
    for b in s.barrier_waves:
        if b not in s.waves:
            errors.append(f"settings.barrier_waves: {b!r} is not a wave")
    for j in m.jobs:
        for d in j.deps:
            if d not in seen:
                errors.append(f"job {j.id!r}: unknown dependency {d!r}")
            elif seen[d].wave_index > j.wave_index:
                errors.append(f"job {j.id!r}: depends on {d!r} of a later wave ({seen[d].wave})")
        for a in j.after:
            if a in s.waves:
                if s.waves.index(a) >= j.wave_index:
                    errors.append(f"job {j.id!r}: 'after' wave {a!r} must be an earlier wave")
            elif a not in seen:
                errors.append(f"job {j.id!r}: unknown 'after' entry {a!r}")
            elif seen[a].wave_index > j.wave_index:
                errors.append(f"job {j.id!r}: 'after' {a!r} is in a later wave")
    if errors:
        return
    # cycles, and the processing order (wave index first, then dependencies)
    edges = {j.id: [x for x in j.deps + j.after if x in seen] for j in m.jobs}
    mark, order = {}, []

    def visit(u, path):
        mark[u] = 1
        for v in edges[u]:
            if mark.get(v) == 1:
                errors.append("dependency cycle: " + " -> ".join(path + [u, v]))
                return
            if mark.get(v) is None:
                visit(v, path + [u])
        mark[u] = 2
        order.append(u)

    for j in sorted(m.jobs, key=lambda x: (x.wave_index, x.index)):
        if mark.get(j.id) is None:
            visit(j.id, [])
    if errors:
        return
    rank = {u: i for i, u in enumerate(order)}
    m.order = sorted(rank, key=lambda u: (seen[u].wave_index, rank[u]))
    m.dependents = {j.id: [] for j in m.jobs}
    for j in m.jobs:
        for d in j.deps:
            m.dependents[d].append(j.id)
    # a job that is never cut must not need a job that can be cut
    for j in m.jobs:
        if j.cut_rank is not None:
            continue
        stack, seen_dep = list(j.deps), set()
        while stack:
            d = stack.pop()
            if d in seen_dep:
                continue
            seen_dep.add(d)
            if seen[d].cut_rank is not None:
                errors.append(f"job {j.id!r} is never cut but needs {d!r} (cut rank {seen[d].cut_rank}); "
                              f"use 'after' for an ordering-only dependency")
                break
            stack.extend(seen[d].deps)


def load_manifest(src) -> Manifest:
    """Parse and validate a manifest (YAML or JSON path, or a dict). Raises ManifestError listing every problem."""
    path, sha = None, None
    if isinstance(src, (str, Path)):
        path = Path(src)
        text = path.read_text(encoding="utf-8")
        sha = hashlib.sha256(text.encode()).hexdigest()
        if path.suffix == ".json":
            data = json.loads(text)
        else:
            import yaml

            data = yaml.safe_load(text) or {}
    else:
        data = src
    errors = []
    if not isinstance(data, dict):
        raise ManifestError(["the manifest must be a mapping with 'settings' and 'jobs'"])
    extra = set(data) - {"settings", "jobs", "version", "notes"}
    if extra:
        errors.append(f"unknown top-level keys {sorted(extra)}")
    s = _parse_settings(data.get("settings") or {}, errors)
    jobs = [j for j in (_parse_job(d, i, s, errors) for i, d in enumerate(data.get("jobs") or [])) if j]
    m = Manifest(s, jobs, path, sha)
    if not errors:
        _validate(m, errors)
    if errors:
        raise ManifestError(errors)
    return m


