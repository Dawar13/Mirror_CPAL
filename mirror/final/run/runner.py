"""Final-phase runner: job manifest, GPU packing, budget governor, projection and cut order, STATUS section.

FINAL_PHASE_PLAN.md v2, Section 7 item 11 and Sections 8 and 9; docs/final_phase_design.md Section 6. The manifest
format is in jobs/final_phase.schema.md; the command line is scripts/fp_runner.py. Successor of
scripts/h100_sched.sh and scripts/h100_sched_core.py, with what the 15 November run taught (notes/decisions.md):
  - a job is keyed by its manifest id, never by its command line, so editing a command never starts a second copy;
  - every job gets the thread caps of settings.env, and host memory is checked as well as GPU memory;
  - a job runs in its own process group (setsid), so stopping the runner leaves jobs running; the runner signals
    only process groups it started itself (pid and start time recorded by its own wrapper);
  - VM time, not calendar time, is budgeted: a pause of the VM (the container starts again) is not counted.

How a job runs. The runner writes logs/final/state/<id>.start and <id>.cmd, then starts a small bash wrapper in a
new session; the wrapper writes <id>.pid ("pid starttime"), runs the command from the repository root with its output
in logs/final/<id>.log, and writes <id>.rc last. <id>.json keeps every attempt. A job has succeeded when its exit
code is 0 and its done marker exists. A job that fails twice (non-zero exit, missing done marker or timeout) stops new
launches (the plan's stop event); so does any settings.stop_when condition (Gate P). Jobs whose process vanished
without an exit code (machine stopped) are started again up to max_lost times.

Choosing a job. Ready jobs (hard dependencies finished, soft "after" dependencies settled, when-conditions true,
barrier waves complete) start one per step, by priority, if
    free GPU GB - GB reserved for GPU jobs started in the last warmup_s - its GB >= headroom_gb,
and, with declared_budget, the declared GB of all running GPU jobs plus its own fit in total - headroom_gb; plus the
host-memory rule, the caps (max_running, max_heals, max_cpu), locks and exclusive jobs. When heals run and the
mean GPU utilisation over util_window_s is below util_target, light and eval jobs go first (packing); otherwise heals
go first (critical path). A job that failed before asks for retry_mem_factor times its memory.

Budget governor. VM hours count from the start of W0 (logs/final/state/budget.json, shared with
scripts/fp_vm_w0.sh). From heal_stop_hours (13.5) no new heal starts and only after_heal_stop_kinds (evaluations,
decisions, report) may start; a heal also waits if its expected end passes ceiling_hours - end_reserve_hours. At
ceiling_hours (15) the runner sends SIGTERM to every process group it started, SIGKILL after term_grace_s, writes
the status and exits (code 3).

Projection and cuts. Before the first job of a wave after W0 starts (every wave with recut_each_wave), the runner
projects the total VM hours:
    used hours + remaining heal-units x hours per unit / concurrency + est_hours of non-overlapping jobs + reserve,
with hours per unit and concurrency measured (W0 timing file, or the finished heal jobs once min_heal_jobs ran) or
set by hand. Above target_hours (13.5) it cuts unstarted jobs in cut_rank order (Section 9), rank by rank with their
dependents, until the projection fits, and appends one line per cut to notes/decisions.md.

Status. Every status_s and after every event the runner rewrites the part of results/STATUS.md between its marker
comments (jobs, waves, GPU, VM hours, projection, cuts, stop events) and logs/final/state/status.json; nvidia-smi is
logged to logs/final/gpu.csv every gpu_log_s seconds. The GPU query, clock, host memory, container start time and
process launcher are injectable, so tests run on CPU. No external sources were used.
"""
