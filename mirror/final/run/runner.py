class RunnerLock:
    """One runner per state directory (flock on Linux, msvcrt elsewhere)."""

    def __init__(self, path: Path):
        self.path, self.fh = Path(path), None

    def acquire(self) -> "RunnerLock":
        self.path.parent.mkdir(parents=True, exist_ok=True)
        fh = open(self.path, "a+")
        try:
            try:
                import fcntl

                fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            except ImportError:
                import msvcrt

                fh.seek(0)
                msvcrt.locking(fh.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError:
            fh.close()
            raise RunnerBusy(f"another runner holds {self.path}")
        self.fh = fh
        return self

    def release(self) -> None:
        if self.fh is not None:
            try:
                try:
                    import fcntl

                    fcntl.flock(self.fh.fileno(), fcntl.LOCK_UN)
                except ImportError:
                    import msvcrt

                    self.fh.seek(0)
                    msvcrt.locking(self.fh.fileno(), msvcrt.LK_UNLCK, 1)
            except OSError:
                pass
            self.fh.close()
            self.fh = None

    def __enter__(self):
        return self.acquire()

    def __exit__(self, *exc):
        self.release()


def update_marked_section(path: Path, body: str) -> None:
    """Replace the text between the runner's marker comments (insert the block after the first '# ' title line,
    or at the top, when the markers are missing). Atomic write; the rest of the file is kept as it is."""
    path = Path(path)
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    block = f"{MARK_BEGIN}\n{body.rstrip()}\n{MARK_END}"
    m = _BEGIN_RE.search(text)
    end = text.find(MARK_END, m.end()) if m else -1
    if m and end >= 0:
        new = text[:m.start()] + block + text[end + len(MARK_END):]
    else:
        lines = text.splitlines(keepends=True)
        at = next((i + 1 for i, ln in enumerate(lines) if ln.startswith("# ")), 0)
        head = "".join(lines[:at])
        if head and not head.endswith("\n"):
            head += "\n"
        new = head + ("\n" if head else "") + block + "\n\n" + "".join(lines[at:]).lstrip("\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".fp_runner.tmp")
    tmp.write_text(new, encoding="utf-8")
    os.replace(tmp, path)


