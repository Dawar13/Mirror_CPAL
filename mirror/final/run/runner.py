@dataclass
class Condition:
    file: str
    key: str | None = None
    op: str = "exists"            # equals, not_equals, in, exists, truthy, falsy
    value: object = None
    reason: str | None = None

    def describe(self) -> str:
        if self.op == "exists":
            return f"{self.file} exists"
        k = self.key or "(file)"
        return f"{self.file}: {k} {self.op.replace('_', ' ')}" + ("" if self.op in ("truthy", "falsy")
                                                                   else f" {self.value!r}")


def parse_condition(d, where: str, errors: list) -> Condition | None:
    if not isinstance(d, dict) or not isinstance(d.get("file"), str):
        errors.append(f"{where}: a condition needs a 'file' (got {d!r})")
        return None
    ops = [k for k in ("equals", "not_equals", "in", "exists", "truthy", "falsy") if k in d]
    extra = set(d) - {"file", "key", "reason", "equals", "not_equals", "in", "exists", "truthy", "falsy"}
    if extra:
        errors.append(f"{where}: unknown condition keys {sorted(extra)}")
    if len(ops) > 1:
        errors.append(f"{where}: one operator per condition, got {ops}")
        return None
    op = ops[0] if ops else ("truthy" if d.get("key") else "exists")
    if op == "in" and not isinstance(d["in"], list):
        errors.append(f"{where}: 'in' needs a list")
    return Condition(d["file"], d.get("key"), op, d.get(op), d.get("reason"))


def eval_condition(c: Condition, root: Path):
    """True or False, or None while the file or key is missing."""
    path = Path(root) / c.file
    if c.op == "exists":
        return path.exists() if c.value in (None, True) else not path.exists()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    v = data
    for part in (c.key or "").split("."):
        if not part:
            continue
        if isinstance(v, dict) and part in v:
            v = v[part]
        else:
            return None
    if c.op == "equals":
        return v == c.value
    if c.op == "not_equals":
        return v != c.value
    if c.op == "in":
        return v in (c.value or [])
    if c.op == "truthy":
        return bool(v)
    if c.op == "falsy":
        return not bool(v)
    return None


